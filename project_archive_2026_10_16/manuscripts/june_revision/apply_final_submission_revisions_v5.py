def set_paragraph_text(paragraph, text: str) -> None:
    for run in paragraph.runs:
        run.text = ""
    if paragraph.runs:
        paragraph.runs[0].text = text
    else:
        paragraph.add_run(text)


def insert_paragraph_before(anchor: Paragraph, text: str, style=None) -> Paragraph:
    new_p = OxmlElement("w:p")
    anchor._p.addprevious(new_p)
    para = Paragraph(new_p, anchor._parent)
    para.style = style or anchor.style
    para.add_run(text)
    return para


def insert_table_before(anchor: Paragraph, rows: list[list[str]], template_table) -> None:
    doc = anchor._parent
    table = doc.add_table(rows=len(rows), cols=len(rows[0]), width=Inches(6.6))
    if template_table is not None:
        table.style = template_table.style
    for r_idx, row in enumerate(rows):
        for c_idx, value in enumerate(row):
            table.cell(r_idx, c_idx).text = value
    anchor._p.addprevious(table._tbl)


