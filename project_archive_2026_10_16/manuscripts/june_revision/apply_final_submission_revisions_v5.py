def insert_weight_sensitivity_section(doc: Document) -> None:
    metrics = pd.read_csv(WEIGHT_CSV)
    anchor = None
    for para in doc.paragraphs:
        if para.text.strip() == "6  讨论":
            anchor = para
            break
    if anchor is None:
        raise RuntimeError("未找到 6 讨论锚点。")

    section_style = anchor.style
    body_style = doc.paragraphs[100].style if len(doc.paragraphs) > 100 else anchor.style
    caption_style = doc.paragraphs[85].style if len(doc.paragraphs) > 85 else body_style
    template_table = doc.tables[-1] if doc.tables else None

    insert_paragraph_before(anchor, "5.7  权重敏感性与不确定性补充测试", section_style)
    insert_paragraph_before(
        anchor,
        "为回应启发式评分权重可能影响候选排序的问题，本文以 6 m 保守型权重为基准，对光照收益、干预体量惩罚和新增阴影惩罚分别进行 ±50% 的单因素扰动，并重新运行算法 B。结果显示，C6/C33 组合只在基准权重和体量惩罚降低两种情况下保持；当光照收益、体量惩罚或阴影惩罚发生较大扰动时，候选可能转向 C6 重复干预或其他组合，且后复算暗区比例未产生改善（见表8）。这一结果说明，算法 B 的启发式权重会影响候选排序，不能被解释为稳定求得唯一最优解；但它也证明了方案后复算的必要性，即只有通过后模拟筛选，才能识别出真正具有暗区改善效果的候选方案。",
        body_style,
    )
    insert_paragraph_before(
        anchor,
        "同时，保守型方案的平均采光小时提升仅约 0.013 h，已经接近简化 2.5D 模型的解释边界。本文因此不把平均采光小时提升作为显著性能结论，而将主要贡献限定为：在统一数据管线下生成可比较候选，利用非 AI 基线、网格敏感性、权重敏感性、局部复核和人工复核共同筛选方案。这种定位更符合旧街区早期设计阶段的辅助决策需求。",
        body_style,
    )
    insert_paragraph_before(anchor, "表8  权重敏感性测试结果", caption_style)

    rows = [["权重扰动", "推荐建筑", "干预体量", "方案后暗区比例", "解释"]]
    explanation = {
        "base": "保守型有效候选",
        "light_minus_50": "候选变化，后复算无暗区改善",
        "light_plus_50": "退化为 C6 重复干预，无暗区改善",
        "volume_minus_50": "仍保持 C6/C33",
        "volume_plus_50": "退化为 C6 重复干预，无暗区改善",
        "shadow_minus_50": "退化为 C6 重复干预，无暗区改善",
        "shadow_plus_50": "退化为 C6 重复干预，无暗区改善",
    }
    for _, row in metrics.iterrows():
        rows.append(
            [
                str(row["variant_label"]),
                str(row["changed_building_ids"]).replace(";", "、").replace("|", "/"),
                f"{float(row['intervention_volume']):.3f}",
                f"{float(row['post_dark_zone_percent']):.2f}%",
                explanation.get(str(row["variant_id"]), ""),
            ]
        )
    insert_table_before(anchor, rows, template_table)


